  static String t(
    BuildContext context,
    String key, {
    Map<String, String>? vars,
  }) {
    final locale = NeoMamaApp.maybeOf(context)?.locale ?? Localizations.localeOf(context);
    return byCode(locale.languageCode, key, vars: vars);
  }

  static String byCode(
    String code,
    String key, {
    Map<String, String>? vars,
  }) {
    final lang = _strings.containsKey(code) ? code : 'en';
    var value = _strings[lang]?[key] ?? _strings['en']?[key] ?? key;
    if (vars != null) {
      vars.forEach((k, v) {
        value = value.replaceAll('{$k}', v);
      });
    }
    return value;
  }
